#!/usr/bin/env python3
"""Regenerate the additional, table-driven Tier 0 assembly cases and expectations.

Run deliberately: this overwrites only the named generated assembly files and
their manifest entries. The original four tests remain unchanged. Expected
arithmetic uses Python's integers, masked explicitly to 32 bits.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = 0xffffffff
FRAME = 0x7800


def main():
    manifest = json.loads((ROOT / "manifest.json").read_text())

    def save(name, body, expectations):
        header = ('/* Generated by tools/expand_cases.py; edit that script to change cases. */\n'
                  '.include "tier0.inc"\nBEGIN_TEST\n\n')
        (ROOT / "tier0" / f"{name}.S").write_text(
            header + "\n".join(body) + "\n\nEND_TEST\n")
        manifest["tests"][name] = [
            [f"0x{value & MASK:08x}", description]
            for value, description in expectations]

    def push(value):
        return f"PUSH32 0x{value & MASK:08x}"

    def write(address, value):
        return [push(value), push(address), "store"]

    def reset_sp():
        return [push(FRAME), "popsp"]

    patterns = [0, 1, 0xff, 0x100, 0x7fff, 0x8000, 0xffff, 0x10000,
                0x7fffff, 0x800000, 0x7fffffff, 0x80000000,
                0xffffffff, 0x01234567, 0x89abcdef, 0xa5a55a5a]
    body, expected = [], []
    for slot, value in enumerate(patterns):
        body += [push(value), f"SAVE {slot}"]
        expected.append((value, f"five-byte IM construction of 0x{value:08x}"))
    save("im_patterns", body, expected)

    body, expected = [], []
    for slot, bits in enumerate(range(1, 33)):
        body += [f"/* Carry propagates through {bits} consecutive one bits. */",
                 push((1 << bits) - 1), push(1), "add", f"SAVE {slot}"]
        expected.append(((1 << bits) & MASK, f"ADD carry through {bits} one bits"))
    save("add_carries", body, expected)

    body, expected = [], []
    for bit in range(32):
        body += [push(1 << bit), "flip", f"SAVE {bit}"]
        expected.append((1 << (31 - bit), f"FLIP bit {bit} to bit {31 - bit}"))
    save("flip_bits", body, expected)

    for operation in ["and", "or", "not"]:
        body, expected = [], []
        for bit in range(32):
            one = 1 << bit
            body += [push(one)]
            if operation != "not":
                body += [push(0xaaaaaaaa)]
            body += [operation, f"SAVE {bit}"]
            value = {"and": one & 0xaaaaaaaa,
                     "or": one | 0xaaaaaaaa, "not": MASK ^ one}[operation]
            expected.append((value, f"{operation.upper()} walking bit {bit}"))
        save(f"{operation}_bits", body, expected)

    body = ["pushsp", "SAVE 0", push(0x11223344), "pushsp", "SAVE 1", "SAVE 2",
            "pushsp", "SAVE 3", *reset_sp(), "pushsp", "SAVE 4",
            "pushsp", "pushsp", "SAVE 5", "SAVE 6", "pushsp", "SAVE 7",
            push(0x7400), "popsp", "pushsp", "SAVE 8",
            "pushsp", "SAVE 9"]
    expected = [(0x7ff8, "PUSHSP reports pre-push SP"),
                (0x7ff4, "pushing one word reduces SP by four bytes"),
                (0x11223344, "PUSHSP and result saving preserve the prior TOS"),
                (0x7ff8, "popping results restores baseline SP"),
                (FRAME, "POPSP selects exactly the supplied address"),
                (FRAME - 4, "second consecutive PUSHSP sees first push"),
                (FRAME, "first consecutive PUSHSP value is preserved"),
                (FRAME, "two saved PUSHSP values leave no stack leak"),
                (0x7400, "POPSP relocates the stack to another valid RAM address"),
                (0x7400, "saving a stack-pointer result leaves SP unchanged")]
    save("stack_pointer", body, expected)

    for half, indices in [("low", range(16)), ("high", range(16, 32))]:
        body, expected = [], []
        for index in indices:
            offset = index * 4
            value = (0x81234500 | index)
            slot = len(expected)
            body += [f"/* LOADSP byte offset {offset}. */", *reset_sp(),
                     *write(FRAME + offset, value), f"loadsp {offset}", f"SAVE {slot}",
                     push(FRAME + offset), "load", f"SAVE {slot + 1}",
                     "pushsp", f"SAVE {slot + 2}"]
            expected += [(value, f"LOADSP {offset}: copied value"),
                         (value, f"LOADSP {offset}: source unchanged"),
                         (FRAME, f"LOADSP {offset}: push then SAVE restores SP")]
        save(f"loadsp_{half}", body, expected)

    for half, indices in [("low", range(16)), ("high", range(16, 32))]:
        body, expected = [], []
        for index in indices:
            offset = index * 4
            slot = len(expected)
            value = 0xcafe0000 | index
            # Before STORESP: SP=FRAME-4, so target=FRAME-4+offset.
            # Offset zero only discards TOS; its old memory slot already holds
            # that same value and may be reused immediately by later pushes.
            target = FRAME + max(0, offset - 4)
            body += [f"/* STORESP byte offset {offset}. */", *reset_sp(),
                     *write(target, 0x11223344),
                     *write(target + 4, 0x55667788), push(value),
                     f"storesp {offset}", push(target), "load", f"SAVE {slot}",
                     push(target + 4), "load", f"SAVE {slot + 1}",
                     "pushsp", f"SAVE {slot + 2}"]
            expected += [(0x11223344 if index == 0 else value,
                          f"STORESP {offset}: " +
                          ("discard preserves old NOS" if index == 0 else "target updated")),
                         (0x55667788, f"STORESP {offset}: higher neighbor unchanged"),
                         (FRAME, f"STORESP {offset}: pops exactly one word")]
        save(f"storesp_{half}", body, expected)

    body, expected = [], []
    for index in range(16):
        offset = index * 4
        slot = len(expected)
        a = 0xffffffff if index == 0 else (0x7ffffff0 + index)
        b = a if index == 0 else (0x10 + index)
        body += [f"/* ADDSP byte offset {offset}; TOS is already at FRAME. */",
                 *reset_sp(), *write(FRAME, a)]
        if index:
            body += write(FRAME + offset, b)
        else:
            body += write(FRAME + 0x100, 0x13579bdf)
        body += [f"addsp {offset}", f"SAVE {slot}", "pushsp", f"SAVE {slot + 1}",
                 push(FRAME + (offset if index else 0x100)), "load", f"SAVE {slot + 2}"]
        expected += [((a + b) & MASK, f"ADDSP {offset}: TOS plus selected word"),
                     (FRAME + 4, f"ADDSP {offset}: replaces TOS, SAVE consumes it"),
                     (b if index else 0x13579bdf,
                      f"ADDSP {offset}: " + ("source preserved" if index else "guard preserved"))]
    save("addsp_offsets", body, expected)

    # Every skipped path changes a value that will actually be checked.
    body = [*write(0x1200, 0x55aa55aa),
            "im forward_target", "poppc", *write(0x1200, 0xbad00001),
            "forward_target:", push(0x1200), "load", "SAVE 0", "pushsp", "SAVE 1",
            "im backward_entry", "poppc",
            "backward_target:", push(0x1234), "SAVE 2", "im backward_after", "poppc",
            "backward_entry:", "im backward_target", "poppc", push(0xbad00002), "SAVE 2",
            "backward_after:", "pushsp", "SAVE 3",
            push(0x89abcdef), "im preserve_target", "poppc", push(0xbad00003),
            "preserve_target:", "SAVE 4", "pushsp", "SAVE 5"]
    expected = [(0x55aa55aa, "forward POPPC skips poison store"),
                (0x7ff8, "forward POPPC consumes target address"),
                (0x1234, "backward POPPC reaches target and returns via explicit jump"),
                (0x7ff8, "backward control flow leaves no stack leak"),
                (0x89abcdef, "POPPC preserves value beneath target address"),
                (0x7ff8, "control-transfer tests restore baseline SP")]
    save("poppc", body, expected)

    body, expected = [], []
    for index, value in enumerate(patterns):
        body += write(0x12e0 + index * 4, value)
    for index, value in enumerate(patterns):
        body += [push(0x12e0 + index * 4), "load", f"SAVE {index}"]
        expected.append((value, f"word pattern at 0x{0x12e0 + index * 4:04x}"))
    for index in range(0, len(patterns), 2):
        body += write(0x12e0 + index * 4, MASK ^ patterns[index])
    for index, value in enumerate(patterns):
        body += [push(0x12e0 + index * 4), "load", f"SAVE {16 + index}"]
        expected.append((value if index % 2 else MASK ^ value,
                         f"alternating overwrite preserves correct word at 0x{0x12e0 + index * 4:04x}"))
    save("memory_patterns", body, expected)

    body = [push(0x89abcdef), "nop", "nop", "nop", "SAVE 0", "pushsp", "SAVE 1",
            ".byte 0xbf", "nop", ".byte 0xc0", "SAVE 2", "SAVE 3"]
    expected = [(0x89abcdef, "NOP preserves TOS"),
                (0x7ff8, "NOP does not push or pop"),
                (0xffffffc0, "NOP separates negative immediate from positive immediate"),
                (63, "NOP keeps the earlier positive immediate as a separate value")]
    save("nop", body, expected)

    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    count = sum(map(len, manifest["tests"].values()))
    print(f"Prepared {len(manifest['tests'])} programs and {count} result checks")


if __name__ == "__main__":
    main()
