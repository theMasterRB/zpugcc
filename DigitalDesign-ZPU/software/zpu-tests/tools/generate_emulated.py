#!/usr/bin/env python3
"""Generate directed handler tests and independent arithmetic expectations.

This does not execute/emulate the CPU. Rebuild images after running it.
Symbols in expectations are resolved from the linked image by run_emulated.py.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = 0xffffffff
GUARD = 0x6a09e667
SP = 0x7800
IMPLEMENTED = {
    34: "loadh", 35: "storeh", 36: "lessthan", 37: "lessthanorequal",
    38: "ulessthan", 39: "ulessthanorequal", 41: "mult", 42: "lshiftright",
    43: "ashiftleft", 45: "call", 46: "eq", 47: "neq", 48: "neg",
    49: "sub", 50: "xor", 51: "loadb", 52: "storeb", 55: "eqbranch",
    56: "neqbranch", 57: "poppcrel", 61: "pushspadd", 63: "callpcrel",
}
UNIMPLEMENTED = {40: "swap", 44: "ashiftright", 53: "div", 54: "mod",
                 58: "config", 59: "pushpc", 60: "syscall", 62: "halfmult"}


def word(value):
    return f"0x{value & MASK:08x}"


def signed(value):
    return value if value < 0x80000000 else value - 0x100000000


class Program:
    def __init__(self, name, opcode):
        self.name, self.opcode = name, opcode
        self.lines, self.expected = [], []

    def emit(self, *lines):
        self.lines.extend(lines)

    def push(self, value):
        if isinstance(value, int):
            self.emit("PUSH32 " + word(value))
        else:
            # Relocatable labels need the assembler's IM relocation machinery;
            # the constant-only PUSH32 macro cannot shift an unresolved symbol.
            self.emit("nop", "im " + value, "nop")

    def save(self, expected, description):
        slot = len(self.expected)
        self.emit(f"SAVE {slot}")
        self.expected.append([word(expected) if isinstance(expected, int) else expected,
                              description])

    def observe(self, expected, description):
        self.save(expected, description)
        self.emit("pushsp")
        self.save(SP - 4, description + ": remaining guard SP")
        self.save(GUARD, description + ": lower stack guard preserved")

    def finish(self):
        if not 1 <= len(self.expected) <= 60:
            raise ValueError(f"{self.name}: too many result slots")
        # Every slot starts unequal to its expectation, including expected zero.
        poison = []
        for slot, (value, _) in enumerate(self.expected):
            value = 0xbadc0ffe if value != "0xbadc0ffe" else 0xdeadbeef
            poison += [f"PUSH32 {word(value)}", f"PUSH32 (RESULTS + {slot} * 4)", "store"]
        source = ["/* Generated by tools/generate_emulated.py. */",
                  '.include "emulated.inc"', "BEGIN_EMULATED", *poison,
                  *self.lines, "END_EMULATED", ""]
        (ROOT / "emulated" / (self.name + ".S")).write_text("\n".join(source))
        return {"opcode": self.opcode, "expected": self.expected}


def generate():
    (ROOT / "emulated").mkdir(exist_ok=True)
    programs = []
    # A is TOS; B is NOS. Comparisons use A-first; SUB uses B-A.
    pairs = [(0, 0), (1, 1), (0, 1), (1, 0), (2, 3), (3, 2),
             (MASK, 1), (1, MASK), (0x80000000, 0x7fffffff),
             (0x7fffffff, 0x80000000), (0x80000000, 0x80000000),
             (MASK, MASK), (0x80000000, MASK), (MASK, 0x80000000),
             (0xaaaaaaaa, 0x55555555), (0x01234567, 0x89abcdef)]
    models = {
        36: lambda a, b: int(signed(a) < signed(b)),
        37: lambda a, b: int(signed(a) <= signed(b)),
        38: lambda a, b: int(a < b), 39: lambda a, b: int(a <= b),
        41: lambda a, b: a * b, 46: lambda a, b: int(a == b),
        47: lambda a, b: int(a != b), 49: lambda a, b: b - a,
        50: lambda a, b: a ^ b,
    }
    for op, model in models.items():
        p = Program(IMPLEMENTED[op], op)
        for a, b in pairs:
            p.push(GUARD); p.push(b); p.push(a); p.emit(f".byte {op}")
            p.observe(model(a, b), f"A={word(a)}, B={word(b)}")
        programs.append(p)

    for op in (48, 61):
        p = Program(IMPLEMENTED[op], op)
        for a in (0, 1, 2, 15, 16, 31, 32, 63, 0x7fffffff,
                  0x80000000, 0xfffffffe, MASK):
            p.push(GUARD); p.push(a); p.emit(f".byte {op}")
            p.observe(-a if op == 48 else (SP - 8) + 4 * a, "operand " + word(a))
        programs.append(p)

    # Every legal 0..31 shift count, plus sign/zero/all-ones inputs.
    # Counts >=32 are intentionally excluded until the project defines them.
    shifts = [(0x89abcdef, n) for n in range(32)]
    shifts += [(v, n) for v in (0, 1, MASK, 0x80000000) for n in (0, 1, 31)]
    for op in (42, 43):
        for chunk in range(0, len(shifts), 16):
            p = Program(f"{IMPLEMENTED[op]}_{chunk // 16 + 1}", op)
            for value, count in shifts[chunk:chunk + 16]:
                p.push(GUARD); p.push(value); p.push(count); p.emit(f".byte {op}")
                expected = value >> count if op == 42 else value << count
                p.observe(expected, f"{word(value)}, shift count {count}")
            programs.append(p)

    for op, width in ((51, 8), (34, 16)):
        p = Program(IMPLEMENTED[op], op)
        for value in (0, MASK, 0x89abcdef, 0x80000001, 0x007f80ff):
            for lane in range(0, 4, width // 8):
                p.push(value); p.push(0x1300); p.emit("store")
                p.push(GUARD); p.push(0x1300 + lane); p.emit(f".byte {op}")
                expected = (value >> (32 - width - 8 * lane)) & ((1 << width) - 1)
                p.observe(expected, f"zero-extended {width}-bit lane {lane} of {word(value)}")
        programs.append(p)

    for op, width in ((52, 8), (35, 16)):
        p = Program(IMPLEMENTED[op], op)
        for value in (0, MASK, 0x12345678):
            for lane in range(0, 4, width // 8):
                for address, contents in ((0x12fc, 0x11223344), (0x1300, 0x89abcdef),
                                          (0x1304, 0x55667788)):
                    p.push(contents); p.push(address); p.emit("store")
                p.push(GUARD); p.push(value); p.push(0x1300 + lane)
                p.emit(f".byte {op}")
                p.push(0x1300); p.emit("load")
                shift = 32 - width - lane * 8
                mask = ((1 << width) - 1) << shift
                result = (0x89abcdef & ~mask) | ((value << shift) & mask)
                desc = f"{width}-bit store {word(value)} at lane {lane}"
                p.observe(result, desc + ": merged word, truncation and untouched lanes")
                for addr, expect in ((0x12fc, 0x11223344), (0x1304, 0x55667788)):
                    p.push(addr); p.emit("load")
                    p.save(expect, desc + f": adjacent word {addr:#x} preserved")
        programs.append(p)

    # Both branch directions, taken and not taken, and non-Boolean conditions.
    for op in (55, 56):
        p = Program(IMPLEMENTED[op], op)
        for case, (backwards, condition) in enumerate(
                (back, cond) for back in (False, True) for cond in (0, 1, MASK, 0x80000000)):
            prefix = f"branch_{case}"
            slot = len(p.expected)
            taken = condition == 0 if op == 55 else condition != 0
            if backwards:
                p.push(prefix + "_setup"); p.emit("poppc", prefix + "_target:")
                p.push(0x13579bdf); p.emit(f"SAVE {slot}")
                p.push(prefix + "_join"); p.emit("poppc", prefix + "_setup:")
            p.push(GUARD); p.push(condition)
            p.push(prefix + "_target - " + prefix + "_op")
            p.emit(prefix + "_op:", f".byte {op}")
            p.push(0x2468ace0); p.emit(f"SAVE {slot}")
            if not backwards:
                p.push(prefix + "_join"); p.emit("poppc", prefix + "_target:")
                p.push(0x13579bdf); p.emit(f"SAVE {slot}")
            p.expected.append([word(0x13579bdf if taken else 0x2468ace0),
                               f"{'backward' if backwards else 'forward'}, condition {word(condition)}"])
            p.emit(prefix + "_join:", "pushsp")
            p.save(SP - 4, "branch consumes condition and offset")
            p.save(GUARD, "branch preserves lower stack guard")
        programs.append(p)

    p = Program("poppcrel", 57)
    for backwards in (False, True):
        prefix = "relative_back" if backwards else "relative_forward"
        if backwards:
            p.push(prefix + "_setup"); p.emit("poppc", prefix + "_target:")
            p.push(0x13579bdf)
            p.push(prefix + "_join"); p.emit("poppc", prefix + "_setup:")
        p.push(GUARD); p.push(prefix + "_target - " + prefix + "_op")
        p.emit(prefix + "_op:", ".byte 57")
        p.push(0xbad00001)
        if not backwards:
            p.push(prefix + "_join"); p.emit("poppc", prefix + "_target:")
            p.push(0x13579bdf)
        p.emit(prefix + "_join:")
        p.observe(0x13579bdf, "POPPCREL " + prefix)
    programs.append(p)

    # Nested calls also exercise saving/restoring a return address across calls.
    for op in (45, 63):
        p = Program(IMPLEMENTED[op], op)
        p.push(GUARD)
        p.push("outer" if op == 45 else "outer - outer_op")
        p.emit("outer_op:", f".byte {op}", "outer_return:", "pushsp")
        p.save(SP - 4, "caller SP restored after nested call")
        p.save(GUARD, "caller lower stack guard preserved")
        p.push("call_done"); p.emit("poppc", "outer:", "loadsp 0")
        p.save("symbol:outer_return", "outer callee receives exact PC+1 return address")
        p.emit("pushsp"); p.save(SP - 8, "outer callee SP includes return address")
        p.push("inner" if op == 45 else "inner - inner_op")
        p.emit("inner_op:", f".byte {op}", "inner_return:", "loadsp 0")
        p.save("symbol:outer_return", "nested return preserves outer return address")
        p.emit("poppc", "inner:", "loadsp 0")
        p.save("symbol:inner_return", "inner callee receives exact PC+1 return address")
        p.emit("pushsp"); p.save(SP - 12, "inner callee SP includes both return addresses")
        p.emit("poppc", "call_done:")
        # CALLPCREL's outer and inner targets are forward. Add a backward call.
        if op == 63:
            p.push("back_setup"); p.emit("poppc", "back_callee:", "loadsp 0")
            p.save("symbol:back_return", "backward relative call PC+1")
            p.emit("poppc", "back_setup:")
            p.push(GUARD); p.push("back_callee - back_op")
            p.emit("back_op:", ".byte 63", "back_return:", "pushsp")
            p.save(SP - 4, "backward relative call restores caller SP")
            p.save(GUARD, "backward relative call preserves guard")
        programs.append(p)

    spec = {
        "handler_source": "../crt0Stuff/crt0.S",
        "layout": {"ram_bytes": 32768, "completion_address": "0x1000",
                   "completion_value": "0x5a505530", "result_address": "0x1010"},
        "entry_pc": "0x2000", "initial_sp": "0x7ff8",
        "implemented": {str(k): v for k, v in IMPLEMENTED.items()},
        "unimplemented": {str(k): v for k, v in UNIMPLEMENTED.items()},
        "tests": {p.name: p.finish() for p in programs},
    }
    (ROOT / "emulated_cases.json").write_text(json.dumps(spec, indent=2) + "\n")
    print(f"Generated {len(programs)} emulated programs, "
          f"{sum(len(p.expected) for p in programs)} result checks, "
          f"{len(IMPLEMENTED)} implemented opcode families")


if __name__ == "__main__":
    generate()
